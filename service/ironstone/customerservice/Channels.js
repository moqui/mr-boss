// Customer Service's channel reads and hooks (impl-customer-service P6, CS-CHANNELS, CS-STACK L8; design-customer-service §3
// ChannelSessions, §9 ChannelRouting, §1 Stack contributions; ChannelServices.xml): what ChannelRouting and ChannelSessions
// show, each limited by CustomerService.js's scope, and the Comms hooks (a case from a mail, a chat message or a voicemail;
// the call-context provider with the caller's open cases). The rules and writes are Mantle's mantle.request
// SupportCaseServices (save#ServiceRoute, preview#ServiceRoute, log#CaseCall, review#HeldRequest, create#Case) and
// RequestServices (create#IntakeToken, remove#IntakeToken), which check their own permission and organization; a hook checks
// the message is the user's to read and its sender a customer the user serves before it calls them.
const lib = ec.resource.script("component://mr-mantle/service/mantle/ledger/EntityLib.js")
const cs = ec.resource.script("component://mr-boss/service/ironstone/customerservice/CustomerService.js")
const config = ec.resource.script("component://mr-boss/service/ironstone/customerservice/Configuration.js")
const mantleChannels = ec.resource.script("component://mr-mantle/service/mantle/request/Channels.js")
const {find, one, rows, denied, ms} = lib

const ROUTE = "mantle.request.support.ServiceRoute"
const L = text => ec.l10n.localize(text)
const blank = value => value == null || String(value).trim() === ""
const stampText = value => (value == null ? "" : ec.l10n.format(new Date(ms(value)), "d MMM yyyy HH:mm"))
const dayText = value => (value == null ? "" : ec.l10n.format(new Date(ms(value)), "d MMM yyyy"))
const enumOptions = enumTypeId =>
    rows("moqui.basic.Enumeration", {enumTypeId})
        .sort((a, b) => Number(a.sequenceNum || 0) - Number(b.sequenceNum || 0))
        .map(row => ({value: row.enumId, label: row.description || row.enumId}))
const caseUrl = requestId => "/qapps/CustomerService/Cases/CaseDetail?requestId=" + encodeURIComponent(requestId)
// a Mantle service called as the user, its refusal thrown with its message (and so its code)
function mantle(name, parameters) {
    const out = ec.service.sync().name(name).parameters(parameters).call() || {}
    if (ec.message.hasError()) {
        const message = ec.message.getErrorsString()
        ec.message.clearErrors()
        throw new Error(message)
    }
    return out
}

// ===== find#ServiceRoutes: ChannelRouting IntakeRoutes =====
// The organization's queues with their routes (mail, the public form, the forum, chat), the Comms mail rules whose
// createRequest action names one of them, each queue's public form token (in effect or not), the requests held for review,
// and the options of RouteEdit and RouteTest. For the settings' users (the administrator saves, the manager reads and
// tests); canEdit with SUPPORT_POLICY_EDIT, canReview with SUPPORT_CASE_EDIT.
function findRoutes(p) {
    const userScope = cs.required()
    const can = userScope.capabilities
    if (!can.policyEdit && !can.caseManage) denied("PERMISSION_DENIED", "SUPPORT_POLICY_EDIT or SUPPORT_CASE_MANAGE is required")
    const organizationPartyId = config.organizationOf(userScope, p.organizationPartyId)
    const queues = cs
        .currentQueues()
        .filter(row => cs.queueOwner(row.requestCategoryId) === organizationPartyId)
        .map(row => ({value: row.requestCategoryId, label: cs.queueName(row.requestCategoryId)}))
        .sort((a, b) => a.label.localeCompare(b.label))
    const queueIds = queues.map(queue => queue.value)
    const routes = queueIds
        .flatMap(requestCategoryId => mantleChannels.currentRoutes({requestCategoryId}))
        .map(row => ({
            serviceRouteId: row.serviceRouteId,
            requestCategoryId: row.requestCategoryId,
            queueText: cs.queueName(row.requestCategoryId),
            channelEnumId: row.channelEnumId,
            channelText: cs.enumText(row.channelEnumId),
            sourceText: mantleChannels.routeText(row),
            emailAccountId: row.emailAccountId || "",
            siteId: row.siteId || "",
            forumContactListId: row.forumContactListId || "",
            requestTypeEnumId: row.requestTypeEnumId || "",
            typeText: row.requestTypeEnumId ? cs.enumText(row.requestTypeEnumId) : L("The queue's first type"),
            defaultPriority: row.defaultPriority != null ? String(row.defaultPriority) : "",
            unknownSenderEnumId: row.unknownSenderEnumId || "",
            senderText: row.unknownSenderEnumId ? cs.enumText(row.unknownSenderEnumId) : L("The service defaults'"),
            autoGeneratedEnumId: row.autoGeneratedEnumId || "SagAttach",
            autoText: cs.enumText(row.autoGeneratedEnumId || "SagAttach"),
            acknowledge: row.acknowledge === "Y" ? "Y" : "N",
            ackText: row.acknowledge === "Y" ? (row.ackTextBlockId ? L("With its text") : L("The standard text")) : L("None"),
            ackTextBlockId: row.ackTextBlockId || "",
            replyEmailIdentityId: row.replyEmailIdentityId || "",
            rateLimitPerHour: row.rateLimitPerHour != null ? String(row.rateLimitPerHour) : "",
            tokenValidDays: row.tokenValidDays != null ? String(row.tokenValidDays) : "",
            lastErrorText: row.lastErrorText ? stampText(row.lastErrorDate) + ": " + row.lastErrorText : "",
            fromText: dayText(row.fromDate)
        }))
    // the Comms rules that file mail into a queue (ErActCreateRequest's value), each named with its account
    const rules = []
    for (const rule of find("moqui.basic.email.EmailRule")
        .condition("actionsJson", "like", "%createRequest%")
        .limit(500)
        .list()) {
        let actions = []
        try {
            actions = JSON.parse(rule.actionsJson || "[]")
        } catch (error) {
            ec.logger.warn("Email rule " + rule.emailRuleId + ": its actions are not JSON, left out of ChannelRouting")
        }
        for (const action of Array.isArray(actions) ? actions : [])
            if (action?.action === "createRequest" && queueIds.includes(String(action.value || "")))
                rules.push({
                    emailRuleId: rule.emailRuleId,
                    ruleName: rule.ruleName || rule.emailRuleId,
                    queueText: cs.queueName(action.value),
                    accountText: one("moqui.basic.email.EmailAccount", {emailAccountId: rule.emailAccountId})?.emailAddress || "",
                    enabledText: rule.enabled === "N" ? L("Off") : L("On")
                })
    }
    // each queue's public form token: in effect until when, or none
    const tokens = queues.map(queue => {
        const active = rows("mantle.party.ExternalAccessCapability", {
            recordType: "RequestCategory",
            recordId: queue.value
        }).filter(row => !row.revokedDate && lib.active(row))[0]
        return {
            requestCategoryId: queue.value,
            queueText: queue.label,
            active: !!active,
            stateText: active ? L("On until") + " " + dayText(active.thruDate) : L("Off")
        }
    })
    const held = mantleChannels.heldRequests([organizationPartyId], 50).map(row => {
        const reporter = rows("mantle.request.RequestParty", {requestId: row.requestId, roleTypeId: "Reporter"}).filter(r =>
            lib.active(r)
        )[0]
        const note = rows("mantle.request.RequestNote", {requestId: row.requestId}).sort(
            (a, b) => Number(ms(b.noteDate)) - Number(ms(a.noteDate))
        )[0]
        return {
            requestId: row.requestId,
            requestName: row.requestName || row.requestId,
            queueText: cs.queueName(row.requestCategoryId),
            fromText: reporter ? cs.partyName(reporter.partyId) : "",
            reasonText: note ? String(note.noteText || "").replace(/^Held for review: /, "") : "",
            channelText: cs.enumText(row.salesChannelEnumId),
            dateText: stampText(row.requestDate)
        }
    })
    const accounts = Array.from(
        find("moqui.basic.email.EmailAccount").condition("statusId", "not-equals", "EasRemoved").limit(100).list()
    )
    const sites = Array.from(find("mantle.public.PublicSite").orderBy("name").limit(100).list())
    const siteIds = sites.map(site => site.siteId)
    const forumCategories = siteIds.length
        ? Array.from(find("mantle.forum.ForumCategory").condition("siteId", "in", siteIds).limit(300).list())
        : []
    const blockFind = find("moqui.basic.email.EmailTextBlock").condition(
        ec.entity.conditionFactory.makeCondition(
            [
                ec.entity.conditionFactory.makeCondition("ownerUserId", "equals", ec.user.userId || "_NONE_"),
                ec.entity.conditionFactory.makeCondition(
                    "userGroupId",
                    "in",
                    Array.from(ec.user.getUserGroupIdSet() || []).concat(["_NONE_"])
                )
            ],
            "or"
        )
    )
    return {
        organizationPartyId,
        organizations: config.organizationOptions(userScope),
        canEdit: !!can.policyEdit,
        canReview: !!can.caseEdit,
        queues,
        routes,
        rules,
        tokens,
        held,
        channelOptions: enumOptions("ServiceRouteChannel"),
        unknownOptions: enumOptions("ServiceUnknownSender"),
        autoOptions: enumOptions("ServiceAutoGenerated"),
        typeOptions: enumOptions("RequestType").sort((a, b) => a.label.localeCompare(b.label)),
        accountOptions: accounts.map(row => ({
            value: row.emailAccountId,
            label: row.emailAddress || row.accountName || row.emailAccountId
        })),
        identityOptions: accounts.length
            ? Array.from(
                  find("moqui.basic.email.EmailIdentity")
                      .condition(
                          "emailAccountId",
                          "in",
                          accounts.map(row => row.emailAccountId)
                      )
                      .limit(200)
                      .list()
              ).map(row => ({value: row.emailIdentityId, label: [row.displayName, row.emailAddress].filter(Boolean).join(" · ")}))
            : [],
        textBlockOptions: Array.from(blockFind.orderBy("title").limit(100).list()).map(row => ({
            value: row.emailTextBlockId,
            label: row.title || row.emailTextBlockId
        })),
        siteOptions: sites.map(row => ({value: row.siteId, label: row.name || row.siteId})),
        forumCategoryOptions: forumCategories.map(row => ({
            value: row.contactListId,
            label:
                (sites.find(site => site.siteId === row.siteId)?.name || row.siteId) +
                " · " +
                (one("mantle.marketing.contact.ContactList", {contactListId: row.contactListId})?.contactListName ||
                    row.slug ||
                    row.contactListId)
        }))
    }
}

// ===== find#ChannelSessions: ChannelSessions SessionFind, SessionList =====
// The calls, chats and mail of a customer the user serves (and its contacts), through Mantle's
// find#PartyCommunicationEvents with the customer audience (no note, internal message or call logged as internal); with no
// customer, those filed on the cases the user sees (most recent cases first). By channel, agent, period and linked or not;
// each with its case when the user sees it.
const channelTypes = {phone: ["Phone"], chat: ["Chat"], email: ["Email"]}
function findSessions(p) {
    const userScope = cs.required()
    const types = channelTypes[p.channel] || ["Phone", "Chat", "Email"]
    const fromMs = blank(p.fromDate) ? null : ms(p.fromDate)
    const thruMs = blank(p.thruDate) ? null : ms(p.thruDate)
    let eventIds = []
    let customerPartyId = null
    if (!blank(p.customerPartyId)) {
        if (!cs.customerOf(userScope, p.customerPartyId))
            denied("RECORD_UNAVAILABLE", "Customer " + p.customerPartyId + " is not available")
        customerPartyId = p.customerPartyId
        const partyIds = [customerPartyId].concat(
            rows("mantle.party.PartyRelationship", {toPartyId: customerPartyId})
                .filter(row => lib.active(row) && ["PrtContact", "PrtEmployee"].includes(row.relationshipTypeEnumId))
                .map(row => row.fromPartyId)
        )
        for (const partyId of Array.from(new Set(partyIds)).slice(0, 20)) {
            const found = lib.call("mantle.party.CommunicationServices.find#PartyCommunicationEvents", {
                partyId,
                audience: "customer",
                communicationEventTypeId: types.join(","),
                pageIndex: 0,
                pageSize: 100
            })
            eventIds.push(...Array.from(found.commEventList || []).map(row => row.communicationEventId))
        }
    } else {
        const queueIds = userScope.queueIds.length ? userScope.queueIds : ["_NONE_"]
        const caseIds = Array.from(
            find("mantle.request.Request")
                .condition("requestCategoryId", "in", queueIds)
                .orderBy("-lastUpdatedStamp")
                .limit(200)
                .list()
        )
            .map(row => row.requestId)
            .filter(requestId => !!one("mantle.request.support.CaseProfile", {requestId}))
        if (caseIds.length)
            eventIds = Array.from(
                find("mantle.request.RequestCommEvent").condition("requestId", "in", caseIds).limit(500).list()
            ).map(row => row.communicationEventId)
    }
    eventIds = Array.from(new Set(eventIds))
    const events = eventIds.length
        ? Array.from(
              find("mantle.party.communication.CommunicationEvent")
                  .condition("communicationEventId", "in", eventIds)
                  .condition("communicationEventTypeId", "in", types)
                  .orderBy("-entryDate")
                  .limit(300)
                  .list()
          )
        : []
    const sessions = []
    for (const event of events) {
        const atMs = ms(event.datetimeStarted) ?? ms(event.entryDate)
        if (fromMs != null && atMs < fromMs) continue
        if (thruMs != null && atMs >= thruMs) continue
        if (!blank(p.agentPartyId) && event.fromPartyId !== p.agentPartyId && event.toPartyId !== p.agentPartyId) continue
        const internal = !!one("mantle.party.communication.CommunicationEventPurpose", {
            communicationEventId: event.communicationEventId,
            purposeEnumId: "CpServiceInternal"
        })
        if (customerPartyId && internal) continue
        const links = rows("mantle.request.RequestCommEvent", {communicationEventId: event.communicationEventId})
        const visible = links
            .map(link => link.requestId)
            .find(requestId => {
                try {
                    cs.recordOf(userScope, "case", requestId)
                    return true
                } catch (error) {
                    return false
                }
            })
        if (p.linked === "Y" && !links.length) continue
        if (p.linked === "N" && links.length) continue
        const outbound = cs.isInternal(event.fromPartyId) || isStaff(event.fromPartyId)
        const participant = outbound ? event.toPartyId : event.fromPartyId
        const minutes =
            ms(event.datetimeEnded) != null && ms(event.datetimeStarted) != null
                ? Math.round((ms(event.datetimeEnded) - ms(event.datetimeStarted)) / 60000)
                : null
        sessions.push({
            communicationEventId: event.communicationEventId,
            timeText: stampText(atMs),
            directionText: outbound ? L("Out") : L("In"),
            participantName: cs.partyName(participant),
            channelText: cs.enumText(event.communicationEventTypeId) || event.communicationEventTypeId,
            subject: event.subject || "",
            durationText: minutes != null && event.communicationEventTypeId === "Phone" ? minutes + " min" : "",
            outcomeText: event.reasonEnumId ? cs.enumText(event.reasonEnumId) : "",
            audienceText: internal ? L("Internal") : L("With the customer"),
            audienceColor: internal ? "warning" : "positive",
            requestId: visible || null,
            caseText: visible ? visible : links.length ? L("Another case") : L("Not on a case"),
            caseUrl: visible ? caseUrl(visible) : null,
            // a recording plays only through Comms, for its owner; linking a case makes none public
            recordingText: L("Through Comms only")
        })
        if (sessions.length >= 100) break
    }
    return {sessions, customerPartyId, customerName: customerPartyId ? cs.partyName(customerPartyId) : ""}
}
// Whether a party is the service side (works for an internal organization).
const isStaff = partyId =>
    !!partyId &&
    rows("mantle.party.PartyRelationship", {fromPartyId: partyId}).some(
        row =>
            lib.active(row) &&
            ["PrtEmployee", "PrtAgent", "PrtMember", "PrtRepresentative"].includes(row.relationshipTypeEnumId) &&
            cs.isInternal(row.toPartyId)
    )

// ===== the call-context provider (CS-STACK L8) =====
// The caller's open cases the user sees, for the ring bar and the call: the parties with the caller's number (the last seven
// digits, then the whole E.164 number), and their open cases as customer or reporter. Comms' own provider answers the
// contacts, so this answers the cases only. At most 10.
function callContext(p) {
    const recordList = []
    const wanted = String(p.number || "").replace(/[^0-9+]/g, "")
    const digits = wanted.replace(/\D/g, "")
    if (digits.length < 7 || !ec.user.userId) return {contactList: [], recordList}
    const userScope = cs.scope()
    if (!userScope.read) return {contactList: [], recordList}
    const factory = ec.entity.conditionFactory
    const last7 = digits.slice(-7)
    const written = [last7, ...["-", " ", "."].map(separator => last7.slice(0, 3) + separator + last7.slice(3))]
    const partyIds = new Set()
    for (const row of find("mantle.party.contact.PartyContactMechTelecomNumber")
        .condition(
            factory.makeCondition(
                written.map(form => factory.makeCondition("contactNumber", "like", "%" + form + "%")),
                "or"
            )
        )
        .conditionDate("fromDate", "thruDate", ec.user.nowTimestamp)
        .limit(60)
        .list()) {
        const local = String(row.areaCode || "") + String(row.contactNumber || "")
        const countryCode = String(row.countryCode || "").replace(/\D/g, "")
        const e164 = countryCode ? "+" + countryCode + local.replace(/\D/g, "") : null
        if (!e164 || e164 === wanted || e164.replace(/\D/g, "").endsWith(digits.slice(-10))) partyIds.add(row.partyId)
    }
    if (!partyIds.size) return {contactList: [], recordList}
    const requestIds = Array.from(
        new Set(
            Array.from(
                find("mantle.request.RequestParty")
                    .condition("partyId", "in", Array.from(partyIds))
                    .condition("roleTypeId", "in", ["Customer", "Reporter"])
                    .conditionDate("fromDate", "thruDate", ec.user.nowTimestamp)
                    .limit(100)
                    .list()
            ).map(row => row.requestId)
        )
    )
    if (!requestIds.length) return {contactList: [], recordList}
    for (const request of find("mantle.request.Request")
        .condition("requestId", "in", requestIds)
        .condition("statusId", "not-in", ["ReqCompleted", "ReqCancelled", "ReqDraft"])
        .orderBy("-requestDate")
        .limit(50)
        .list()) {
        if (!one("mantle.request.support.CaseProfile", {requestId: request.requestId})) continue
        try {
            cs.recordOf(userScope, "case", request.requestId)
        } catch (error) {
            continue
        }
        recordList.push({
            title: L("Case") + " " + request.requestId + ": " + (request.requestName || ""),
            status: cs.statusText(request.statusId),
            url: caseUrl(request.requestId)
        })
        if (recordList.length >= 10) break
    }
    return {contactList: [], recordList}
}

// ===== the Comms hooks: a case from a mail, a chat message or a voicemail =====
// The organization a case from a message goes to: the queue's, else the customer's owner when it is one of the user's, else
// the user's active or first service organization.
function organizationFor(userScope, customerPartyId, requestCategoryId) {
    if (requestCategoryId) return cs.queueOwner(requestCategoryId)
    const owner = one("mantle.party.Party", {partyId: customerPartyId})?.ownerPartyId
    const ids = cs.vendorIds(userScope)
    if (owner && ids.includes(owner)) return owner
    return userScope.activeOrganizationPartyId || ids[0] || null
}
// The customer a sender stands for: itself when it is a customer the user serves, else the customer it is a current contact
// of; never staff.
function customerOfSender(userScope, partyId) {
    if (!partyId) return null
    if (cs.isInternal(partyId) || isStaff(partyId)) return null
    if (cs.customerOf(userScope, partyId)) return {customerPartyId: partyId, contactPartyId: partyId}
    const relationship = rows("mantle.party.PartyRelationship", {fromPartyId: partyId}).find(
        row =>
            lib.active(row) &&
            ["PrtContact", "PrtEmployee"].includes(row.relationshipTypeEnumId) &&
            cs.customerOf(userScope, row.toPartyId)
    )
    return relationship ? {customerPartyId: relationship.toPartyId, contactPartyId: partyId} : null
}
function requireSender(userScope, partyId) {
    const found = customerOfSender(userScope, partyId)
    if (!found) denied("CUSTOMER_UNAVAILABLE", "The sender is not a customer you serve; make the request in Commons instead")
    return found
}
// A case from a channel message: create#Request (Submitted, the sender its reporter, the customer, the queue given else the
// type's or the policy's default) and Mantle's ensure#CaseProfile at once, with the message it came from, so the case has its
// profile when the hook answers (F84). Not create#Case: a channel case has no template values yet, and create#Case checks the
// queue's template (P7); the case rule takes no template values, as mail and the forum do. Both run with authorization off
// (the raw request create is no Customer Service group's): the user's access, the queue and the sender are checked here.
const mantleCases = ec.resource.script("component://mr-mantle/service/mantle/request/SupportCases.js")
function createCase(userScope, sender, p, extra) {
    if (!userScope.capabilities.caseEdit) denied("PERMISSION_DENIED", "SUPPORT_CASE_EDIT is required")
    if (p.requestCategoryId && !userScope.queueIds.includes(p.requestCategoryId))
        denied("QUEUE_UNAVAILABLE", "Queue " + p.requestCategoryId + " is not available")
    const organizationPartyId = organizationFor(userScope, sender.customerPartyId, p.requestCategoryId)
    if (!organizationPartyId || !cs.vendorIds(userScope).includes(organizationPartyId))
        denied("RECORD_UNAVAILABLE", "Organization " + (organizationPartyId || "") + " is not available")
    const policy = mantleCases.policyOf(organizationPartyId)
    if (!policy) denied("SERVICE_NOT_CONFIGURED", "Customer Service is not set up for " + cs.partyName(organizationPartyId))
    const type = mantleCases.currentRow("mantle.request.support.ServiceRequestType", {
        organizationPartyId,
        requestTypeEnumId: "RqtSupport"
    })
    const requestCategoryId =
        p.requestCategoryId || (type?.serviceEnabled === "Y" ? type.defaultCategoryId : null) || policy.defaultCategoryId || null
    if (!requestCategoryId || cs.queueOwner(requestCategoryId) !== organizationPartyId)
        denied("QUEUE_UNAVAILABLE", "Choose a service queue of " + cs.partyName(organizationPartyId))
    const requestId = lib.call("mantle.request.RequestServices.create#Request", {
        requestName: extra.requestName,
        description: extra.description,
        statusId: "ReqSubmitted",
        requestTypeEnumId: "RqtSupport",
        requestCategoryId,
        priority: type?.defaultPriority ?? 5,
        salesChannelEnumId: extra.salesChannelEnumId,
        filedByPartyId: sender.contactPartyId || sender.customerPartyId,
        customerPartyId: sender.customerPartyId
    }).requestId
    const made = lib.call("mantle.request.SupportCaseServices.ensure#CaseProfile", {
        requestId,
        communicationEventId: extra.communicationEventId || null,
        emailMessageId: extra.emailMessageId || null
    })
    if (!made.isCase) denied("NOT_A_CASE", "Request " + requestId + " is not a case: " + (made.reason || ""))
    return requestId
}
function caseFromMessage(p) {
    const userScope = cs.required()
    if (!userScope.capabilities.caseEdit) denied("PERMISSION_DENIED", "SUPPORT_CASE_EDIT is required")
    if (p.kind === "email") {
        // the message as the user may read it (the Inbox's own check); another's is not found
        const detail = ec.service
            .sync()
            .name("org.moqui.comms.InboxServices.run#Operation")
            .parameters({operation: "get#MessageDetail", parameters: {emailMessageId: p.emailMessageId}})
            .call()?.result?.detail
        ec.message.clearErrors()
        const message = detail ? one("moqui.basic.email.EmailMessage", {emailMessageId: p.emailMessageId}) : null
        if (!message) denied("RECORD_UNAVAILABLE", "Message " + (p.emailMessageId || "") + " is not available")
        const filed = rows("mantle.request.RequestEmailMessage", {emailMessageId: message.emailMessageId})[0]
        if (filed) denied("ALREADY_FILED", "This message is already on request " + filed.requestId)
        const sender = requireSender(userScope, partyOfAddress(message.fromAddress))
        const requestId = createCase(userScope, sender, p, {
            requestName:
                String(message.subject || "")
                    .trim()
                    .substring(0, 255) || L("(no subject)"),
            description: String(message.bodyText || "").substring(0, 20000) || null,
            salesChannelEnumId: "ScEmail",
            emailMessageId: message.emailMessageId
        })
        lib.call("mantle.request.RequestServices.file#RequestEmail", {requestId, emailMessageId: message.emailMessageId})
        return made(requestId, L("Case ${id} made from the message"))
    }
    if (p.kind === "chat") {
        const found = mantle("mantle.party.CommunicationServices.findOrCreate#ChatCommunicationEvent", {
            chatRoomId: p.chatRoomId,
            eventSeq: p.eventSeq
        })
        const chat = found.chatMessage || {}
        if (rows("mantle.request.RequestCommEvent", {communicationEventId: found.communicationEventId}).length)
            denied("ALREADY_FILED", "This message is already on a request")
        const sender = requireSender(userScope, chat.senderPartyId)
        const text = String(chat.bodyText || "").trim()
        const firstLine = text.split(/\r?\n/).find(line => line.trim()) || L("Chat message")
        const requestId = createCase(userScope, sender, p, {
            requestName: firstLine.substring(0, 100),
            description: text.substring(0, 20000) || null,
            salesChannelEnumId: "ScChat",
            communicationEventId: found.communicationEventId
        })
        mantle("mantle.party.CommunicationServices.link#CommunicationEventRecord", {
            communicationEventId: found.communicationEventId,
            recordEntityName: "mantle.request.Request",
            recordId: requestId
        })
        return made(requestId, L("Case ${id} made from the chat message"))
    }
    if (p.kind === "voicemail") {
        const out =
            ec.service
                .sync()
                .name("org.moqui.impl.VoicemailServices.get#Voicemail")
                .parameters({voicemailId: p.voicemailId})
                .call() || {}
        ec.message.clearErrors()
        const voicemail = out.voicemail
        if (!voicemail) denied("RECORD_UNAVAILABLE", "Voicemail " + (p.voicemailId || "") + " is not available")
        const caller = callerParty(voicemail.fromNumber)
        const sender = requireSender(userScope, caller)
        const requestId = createCase(userScope, sender, p, {
            requestName: (L("Voicemail from") + " " + (voicemail.fromName || voicemail.fromNumber || "")).substring(0, 255),
            description: voicemail.transcriptText || null,
            salesChannelEnumId: "ScPhone"
        })
        // the voicemail as an inbound call on the case: its transcript, never its audio (a recording plays only through Comms)
        mantle("mantle.request.SupportCaseServices.log#CaseCall", {
            requestId,
            contactPartyId: caller,
            direction: "in",
            occurredDate: voicemail.receivedDate ? new Date(Number(voicemail.receivedDate)) : null,
            durationMinutes: Math.round(Number(voicemail.durationMs || 0) / 60000),
            summary: voicemail.transcriptText || L("Voicemail") + " " + (voicemail.fromNumber || ""),
            outcomeEnumId: "CcoVoicemail"
        })
        return made(requestId, L("Case ${id} made from the voicemail"))
    }
    throw new Error("Unknown message kind " + p.kind)
}
function made(requestId, words) {
    return {
        recordEntityName: "mantle.request.Request",
        recordId: requestId,
        url: caseUrl(requestId),
        message: ec.resource.expand(words, "", {id: requestId})
    }
}
// The party of an address and of a number, as the intake finds them (a user account's party first).
function partyOfAddress(address) {
    const email = String(address || "")
        .trim()
        .toLowerCase()
    if (!email.includes("@")) return null
    const user = rows("moqui.security.UserAccount", {emailAddress: email}).find(row => row.partyId)
    if (user) return user.partyId
    const info = Array.from(
        find("mantle.party.contact.PartyContactMechInfo", {infoString: email})
            .conditionDate("fromDate", "thruDate", ec.user.nowTimestamp)
            .list()
    ).find(row => {
        const party = one("mantle.party.PartyDetail", {partyId: row.partyId})
        return party && party.disabled !== "Y" && !party.privateOwnerUserId
    })
    return info?.partyId || null
}
function callerParty(number) {
    const digits = String(number || "").replace(/\D/g, "")
    if (digits.length < 7) return null
    const last7 = digits.slice(-7)
    const factory = ec.entity.conditionFactory
    const written = [last7, ...["-", " ", "."].map(separator => last7.slice(0, 3) + separator + last7.slice(3))]
    const row = Array.from(
        find("mantle.party.contact.PartyContactMechTelecomNumber")
            .condition(
                factory.makeCondition(
                    written.map(form => factory.makeCondition("contactNumber", "like", "%" + form + "%")),
                    "or"
                )
            )
            .conditionDate("fromDate", "thruDate", ec.user.nowTimestamp)
            .limit(20)
            .list()
    ).find(candidate =>
        (String(candidate.areaCode || "") + String(candidate.contactNumber || "")).replace(/\D/g, "").endsWith(digits.slice(-10))
    )
    return row?.partyId || null
}

// ===== get#CaseForumTopic: CaseDetail's Reply publicly in forum (F12) =====
// The PASS forum topic a case was escalated from (its PublicDiscussionLink, source case), for a case the user sees; null when
// it came from none.
function caseForumTopic(p) {
    const userScope = cs.required()
    cs.recordOf(userScope, "case", p.requestId)
    const link = rows("mantle.public.PublicDiscussionLink", {sourceType: "case", sourceId: p.requestId}).find(
        row => !row.detachedAt
    )
    if (!link) return {topic: null}
    const root = one("mantle.party.communication.CommunicationEvent", {communicationEventId: link.rootCommEventId})
    return {topic: {siteId: link.siteId, rootCommEventId: link.rootCommEventId, title: root?.subject || ""}}
}

